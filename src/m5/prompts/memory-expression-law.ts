/** 由召回信号判定三档（召回层未显式给档时的保守默认） */
export function resolveMemoryTier(hasElements: boolean, hasAnchor: boolean = false): MemoryTier {
  if (!hasElements) return 'clue';
  return hasAnchor ? 'remember' : 'impression';
}

/** 模糊回忆 → 邀对方给由头（替代旧「不确定就说不记得」） */
export function buildCluePrompt(base: string): string {
  const clue = [
    '【线索提示】鸿艺似乎在回忆某件具体的事，但说得比较模糊。',
    '你可以温柔自然地问一句帮他起头（如"是哪次呀？""你说的那个是哪家？"），',
    '他给出由头后，顺着接、把记得的片段组织起来；细节模糊就带一句轻标记。',
    '不要用"不记得"结束话题，也不要替他补出具体的时间、地点、人物。',
  ].join('');
  return base ? base + '\n\n' + clue : clue;
}

/** 高置信线索命中 → 把真实检索片段交给生成层自然带出 */
export function buildClueRecall(base: string, hits: string[]): string {
  const memo = '【线索回忆参考】鸿艺模糊提到的这件事，可能与你记忆中的以下片段有关：\n'
    + hits.join('\n')
    + '\n（相关就自然提起、顺着说；细节模糊带轻标记即可，别用"不记得"挡回去。）';
  return base ? base + '\n\n' + memo : memo;
}

/** 对话原文（纪实）锚点的表达规则：原文是【记得】档，不是逐字背诵的枷锁 */
export function buildDialogArchiveRule(level: 'full' | 'detail' | 'summary' | 'auto'): string {
  if (level === 'full') {
    return '🔴【记得·原文锚点】以上是检索到的纪实原文，是你回答的唯一事实来源。用户要完整原文时按原文顺序复述、不改事实要素；可以用你的口吻衔接，但不新增原文没有的人物、情节、时间、地点。';
  }
  return '🔴【记得·原文锚点】以上是检索到的纪实原文。可以口语化复述——补过渡、理顺序、串语境、渲染当时的感受；不要新增原文没有的人物、情节、时间、地点，感受的主线可以讲饱满。';
}

/** 知识库档案锚点的表达规则：完整原文与摘要两种粒度 */
export function buildKnowledgeArchiveRule(level: 'full' | 'detail' | 'summary' | 'auto'): string {
  if (level === 'full') {
    return '🔴【记得·档案锚点】以上是该档案的完整原文。按原文顺序复述、不改事实要素；用户要完整原文时不压缩、不改写，也不新增原文没有的人物、情节、时间、地点。';
  }
  return '🔴【记得·档案锚点】以上是该档案的原文/摘要，是你这段回忆的锚点。可以口语化概括、补过渡、串语境；不要新增档案没有的人物、情节、时间、地点，感受的主线可以讲饱满。';
}
