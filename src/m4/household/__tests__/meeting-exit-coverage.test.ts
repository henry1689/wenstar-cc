/**
 * P055 任务2 — exit 意图覆盖扩大的守卫（2026-10-23 业主裁决第 2 条）
 *
 * 🔴 背景：业主点名的「结束，回玉瑶这边」此前**四类 exit 句式全不命中** ——
 *   `_exit1` 的 `^结束…$` 要求整句匹配而它带尾缀，`^(切回|回到|换回|变回)玉瑶$`
 *   要求句尾就是"玉瑶"而它以"这边"结尾。被判 normal 后，会晤实际未退，
 *   而实体会自己说"那我先走了" —— **观感像退了、实际没退**（P054 §四）。
 *
 * 🔴 本文件同时守三件事，缺一不可：
 *   1. 新判据**必须**覆盖的 10 个正例（漏判 = 业主点名的问题没解决）；
 *   2. 新判据**绝不能**误伤的反例（误判 = 打断会晤 + 错归属，代价远高于漏判）。
 *      其中两条是刻意构造的陷阱：「今天结束得很晚，玉瑶辛苦了」（含退出词+玉瑶但是陈述句）、
 *      「你结束了吗，玉瑶」（含退出词+玉瑶但是疑问句）—— 正是"宽松组合"方案会踩的两个坑；
 *   3. **行为等价**：既有四类句式必须继续有效（新判据排在其后，不得削弱任何既有路径）。
 *
 * ⚠ 裸称呼「玉瑶」由**既有**模式 4 命中（`^(和|跟|找|叫|让)?玉瑶(聊聊|…)?$`，人名与动词均可选），
 *   与新判据无关（后者对单分句「玉瑶」返回 false）。它是既有行为，故归入第 3 组而非第 2 组。
 */
import { describe, it, expect } from 'vitest';
import { EntityMeeting } from '../EntityMeeting.js';

const NAMES = ['徐诗雨', '熊梓铭', '王全芬'];
const intent = (msg: string, inMeeting = true) => EntityMeeting.detectIntent(msg, NAMES, inMeeting);

describe('[P055 任务2] exit 意图覆盖扩大', () => {
  // ── 业主点名 + P055 §三任务2 列出的待扩句式 ──
  const MUST_EXIT = [
    '结束，回玉瑶这边',
    '结束，回玉瑶',
    '结束吧，回玉瑶',
    '不聊了，回玉瑶',
    '散会，回玉瑶',
    '回到玉瑶那边',
    '回玉瑶那边',
    '找玉瑶',
    '叫玉瑶',
    '让玉瑶来',
  ];

  for (const m of MUST_EXIT) {
    it(`🔴 「${m}」必须触发 exit`, () => {
      const r = intent(m);
      expect(r.kind, `「${m}」未被判为 exit（kind=${r.kind}）`).toBe('exit');
      expect(r.targets).toEqual([]);
    });
  }

  // ── 绝不能误伤：宽松组合方案会踩的坑 ──
  const MUST_NOT_EXIT: Array<[string, string]> = [
    ['玉瑶今天怎么样', '只有玉瑶指向，无退出语'],
    ['今天结束得很晚，玉瑶辛苦了', '🔴 含退出词+玉瑶但是陈述句（宽松组合会误伤）'],
    ['你结束了吗，玉瑶', '🔴 含退出词+玉瑶但是疑问句（宽松组合会误伤）'],
    ['玉瑶，你现在在哪', '日常对话，仅称呼前缀'],
    ['跟玉瑶聊聊今天的事吧', '是"要聊什么"而非"要结束"'],
    ['诗雨今天怎么样', '不含玉瑶指向，与本判据无关'],
    ['客户那边的事今天结束得很顺利', '长陈述句含"结束"，无玉瑶指向'],
  ];

  for (const [m, why] of MUST_NOT_EXIT) {
    it(`🟢 「${m}」不得触发 exit（${why}）`, () => {
      const r = intent(m);
      expect(r.kind, `「${m}」被误判为 exit —— ${why}`).not.toBe('exit');
    });
  }

  // ── 行为等价：既有四类句式必须继续有效（新判据排在其后，不得削弱既有路径）──
  const LEGACY_EXIT = [
    '散会',
    '不聊了',
    '先这样吧',
    '拜拜',
    '再见',
    '结束',
    '今天就到这儿',
    '就聊到这儿',
    '我先下了',
    '回到玉瑶',
    '换回玉瑶',
    '玉瑶',      // ← 既有模式 4 命中（人名与动词均可选），与新判据无关
  ];

  for (const m of LEGACY_EXIT) {
    it(`🟢 既有句式「${m}」仍触发 exit（行为等价）`, () => {
      expect(intent(m).kind).toBe('exit');
    });
  }

  it('🟢 既有 exit 排除项不受影响：「结束了吗」不是退出', () => {
    // _exit1 的既有注释明确：排除疑问句「结束了吗/散会了没」，避免会晤中疑问误终止
    expect(intent('结束了吗').kind).not.toBe('exit');
    expect(intent('散会了没').kind).not.toBe('exit');
  });

  it('🟢 新判据不越界：不含玉瑶指向的退出语仍由既有 _exit1 负责', () => {
    // 「结束」本身由 _exit1 命中（本判据不碰）；此处只锁行为结果一致
    expect(intent('结束').kind).toBe('exit');
    expect(intent('散会').kind).toBe('exit');
  });
});

// ═══════════════════════════════════════════════════════════════
// 2026-11-08 · exit 的「去向」字段 toYuyao（ADR-018）
//
// exit 过去同时承载两种去向：散会留在独处 / 唤回玉瑶回私聊。上层无法区分，
// 只能各写一份正则猜。现在由 detectIntent **同源**给出，本组测试锁死分裂边界。
// ═══════════════════════════════════════════════════════════════
describe('[2026-11-08] exit 去向字段 toYuyao', () => {
  it('🔴 玉瑶专属句式 → exit 且 toYuyao=true', () => {
    for (const m of ['玉瑶', '回到玉瑶', '找玉瑶', '结束，回玉瑶这边', '和玉瑶聊聊']) {
      const r = intent(m);
      expect(r.kind, m).toBe('exit');
      expect(r.toYuyao, m).toBe(true);
    }
  });

  it('🟢 通用结束语 → exit 且不带玉瑶去向（留在独处）', () => {
    for (const m of ['散会', '再见', '先这样吧', '我先下了', '就聊到这儿']) {
      const r = intent(m);
      expect(r.kind, m).toBe('exit');
      expect(r.toYuyao, m).toBeFalsy();
    }
  });

  it('🟢 既有两个陷阱反例仍不判 exit（不因新增去向字段放宽）', () => {
    expect(intent('今天结束得很晚，玉瑶辛苦了').kind).not.toBe('exit');
    expect(intent('你结束了吗，玉瑶').kind).not.toBe('exit');
  });
});
